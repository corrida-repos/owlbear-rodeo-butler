/**
 * Writes src/core/costlyComponents.ts: every spell whose Material component a spellcasting focus or component pouch
 * can't replace (it has a cost, or the spell consumes it), from the 5etools spell files.
 * Usage: download data/spells/*.json from the 5etools mirror into a folder, then
 *   npx tsx scripts/build-costly-components.ts <folder>
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
if (!dir) throw new Error("Pass the folder with the 5etools spells-*.json files.");
const clean = (s: string) => s.replace(/\{@\w+ ([^{}|]*)(\|[^{}]*)?\}/g, "$1");
const out: Record<string, { "2024"?: string; "2014"?: string }> = {};
for (const f of readdirSync(dir).filter((x) => /^spells-.*\.json$/.test(x)).sort()) {
  const list = JSON.parse(readFileSync(join(dir, f), "utf8")).spell ?? [];
  for (const s of list) {
    const m = s.components?.m;
    if (!m || typeof m !== "object" || !(m.cost || m.consume)) continue;
    const key = String(s.name).toLowerCase();
    const text = clean(String(m.text ?? ""));
    const e = (out[key] ??= {});
    // The 2024 PHB's version for 5.5E rooms, the 2014 PHB's for 5E; other books fill either gap.
    if (s.source === "XPHB") e["2024"] = text;
    else if (s.source === "PHB") e["2014"] = text;
    else { e["2024"] ??= text; e["2014"] ??= text; }
  }
}
const keys = Object.keys(out).sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join("\n");
writeFileSync("src/core/costlyComponents.ts", `/**
 * Spells whose Material component can't be replaced by a spellcasting focus or a component pouch: it has a cost, or
 * the spell consumes it (PHB 2024 and 2014). Generated by scripts/build-costly-components.ts from the 5etools spell
 * data; don't edit by hand. Keys are lowercase spell names; values are the component, per edition.
 */
export const COSTLY_COMPONENTS: Record<string, { "2024"?: string; "2014"?: string }> = {
${body}
};
`);
console.log(`${keys.length} spells`);
