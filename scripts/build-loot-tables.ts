/**
 * Writes src/core/lootTables.ts: the 2024 DMG Arcana / Armaments / Implements / Relics magic item tables the
 * dead-monster loot suggestion rolls on, from the 5etools loot data.
 * Usage: download data/loot.json from the 5etools mirror, then
 *   npx tsx scripts/build-loot-tables.ts <path to loot.json>
 */
import { readFileSync, writeFileSync } from "node:fs";

const file = process.argv[2];
if (!file) throw new Error("Pass the path to 5etools' loot.json.");
const loot = JSON.parse(readFileSync(file, "utf8"));

/** "{@item Cloak of Billowing|XDMG}" → "Cloak of Billowing"; a tag's display text wins when it has one. */
const clean = (s: string) => s.replace(/\{@\w+ ([^{}]*)\}/g, (_, body: string) => {
  const parts = body.split("|");
  return parts[2] || parts[0]!;
});
const refName = (ref: string) => ref.split("|")[0]!;

const THEMES = ["Arcana", "Armaments", "Implements", "Relics"];
const RARITIES = ["Common", "Uncommon", "Rare", "Very Rare", "Legendary"];
const themes: Record<string, Record<string, { min: number; max: number; name: string; options?: string[] }[]>> = {};
for (const theme of THEMES) {
  themes[theme] = {};
  for (const rarity of RARITIES) {
    const t = (loot.magicItems as any[]).find((x) => x.source === "XDMG" && x.name === `${theme} - ${rarity}`);
    if (!t) throw new Error(`No ${theme} - ${rarity} table in loot.json`);
    const rows = (t.table as any[]).map((r) => {
      const fromItems: string[] = (r.choose?.fromItems ?? []).map(refName);
      if (!r.item) return { min: r.min as number, max: r.max as number, name: refName(r.choose.fromGeneric[0]) };
      // A row naming one of several variants ("Spell Scroll (cantrip or level 1 spell)") lists them; Butler rolls one.
      const tags = [...String(r.item).matchAll(/\{@item ([^|}]+)/g)].map((m) => m[1]!);
      const variants = tags.length > 1 ? tags.slice(1) : fromItems.length > 1 ? fromItems : [];
      const base = { min: r.min as number, max: r.max as number };
      if (variants.length === 1) return { ...base, name: variants[0]! };
      if (variants.length > 1) return { ...base, name: tags[0]!, options: variants };
      return { ...base, name: clean(String(r.item)) };
    });
    if (rows[0]!.min !== 1 || rows[rows.length - 1]!.max !== 100) throw new Error(`${theme} - ${rarity} doesn't cover 1–100`);
    themes[theme][rarity] = rows;
  }
}

const json = (x: unknown) => JSON.stringify(x);
writeFileSync("src/core/lootTables.ts", `/**
 * DMG treasure tables for the dead-monster loot suggestion (see loot.ts). Generated by scripts/build-loot-tables.ts
 * from the 5etools loot data; don't edit by hand.
 */
export interface ThemeRow { min: number; max: number; name: string; options?: string[] }

/** 2024 DMG magic item tables by theme and rarity (d100). */
export const THEME_TABLES: Record<"Arcana" | "Armaments" | "Implements" | "Relics", Record<"Common" | "Uncommon" | "Rare" | "Very Rare" | "Legendary", ThemeRow[]>> = ${json(themes)};
`);
console.log("wrote src/core/lootTables.ts");
